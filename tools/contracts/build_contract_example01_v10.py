def run_fmt(run, bold=False):
    run.font.name = FONT
    run._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    run.font.size = SIZE
    run.bold = bold


def add_p(doc, text, align=WD_ALIGN_PARAGRAPH.JUSTIFY, bold=False, after=0, before=0):
    p = doc.add_paragraph()
    run_fmt(p.add_run(text), bold)
    p.alignment = align
    pf = p.paragraph_format
    pf.line_spacing = LINE
    pf.space_after = Pt(after)
    pf.space_before = Pt(before)
    return p


def add_section(doc, text):
    return add_p(doc, text, WD_ALIGN_PARAGRAPH.LEFT, True, 6, 6)


def set_cell_font(cell, bold=False, size=Pt(11)):
    for p in cell.paragraphs:
        for run in p.runs:
            run_fmt(run, bold)
            run.font.size = size


def add_table(doc, headers, rows):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        c = table.rows[0].cells[i]
        c.text = h
        set_cell_font(c, True)
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            c = table.rows[ri + 1].cells[ci]
            c.text = str(val)
            set_cell_font(c)
    add_p(doc, "", after=6)
    return table


